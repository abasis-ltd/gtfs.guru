#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct NoticeGuide {
    title: String,
    meaning: String,
    impact: String,
    fix_steps: Vec<String>,
    files_to_check: Vec<String>,
    verification: String,
    example: Option<NoticeExample>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct NoticeExample {
    assumption: String,
    before: String,
    after: String,
}

fn load_guides(
    schemas: &BTreeMap<String, NoticeSchema>,
) -> anyhow::Result<BTreeMap<String, NoticeGuide>> {
    let guides: BTreeMap<String, NoticeGuide> =
        serde_json::from_str(include_str!("../notice_guides.json"))
            .context("parse notice guide content")?;
    for code in schemas.keys() {
        if !guides.contains_key(code) {
            bail!("published notice `{code}` needs a repair guide");
        }
    }
    for (code, guide) in &guides {
        if !schemas.contains_key(code) {
            bail!("notice guide references unpublished code `{code}`");
        }
        if [
            &guide.title,
            &guide.meaning,
            &guide.impact,
            &guide.verification,
        ]
        .iter()
        .any(|text| text.trim().is_empty())
            || guide.fix_steps.len() < 2
            || guide.fix_steps.iter().any(|step| step.trim().is_empty())
        {
            bail!("notice guide `{code}` has incomplete repair guidance");
        }
        if let Some(example) = &guide.example {
            if [&example.assumption, &example.before, &example.after]
                .iter()
                .any(|text| text.trim().is_empty())
            {
                bail!("notice guide `{code}` has an incomplete example");
            }
        }
    }
    Ok(guides)
}

fn main() -> anyhow::Result<()> {
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    generate(check)
}

fn generate(check: bool) -> anyhow::Result<()> {
    let schemas = build_notice_schema_map();
    let guides = load_guides(&schemas)?;
    let related = build_related_notices(&schemas);

    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let root = manifest_dir.join("../../website");
    let mut changed = Vec::new();

    let notices_dir = root.join("notices");
    if !check {
        fs::create_dir_all(&notices_dir)
            .with_context(|| format!("create {}", notices_dir.display()))?;
    }

    check_or_write(
        &notices_dir.join("notice.css"),
        NOTICE_CSS,
        check,
        &mut changed,
    )?;
    check_or_write(
        &notices_dir.join("notice.js"),
        NOTICE_JS,
        check,
        &mut changed,
    )?;
    check_or_write(
        &notices_dir.join("index.html"),
        &render_index(&schemas, &guides),
        check,
        &mut changed,
    )?;

    for (code, schema) in &schemas {
        let dir = notices_dir.join(code);
        if !check {
            fs::create_dir_all(&dir).with_context(|| format!("create {}", dir.display()))?;
        }
        check_or_write(
            &dir.join("index.html"),
            &render_notice_page(
                schema,
                &guides[code],
                related.get(code).map(Vec::as_slice).unwrap_or_default(),
                &guides,
            ),
            check,
            &mut changed,
        )?;
    }

    let surface = spec_surface();
    let compatibility_dir = root.join("compatibility");
    if !check {
        fs::create_dir_all(&compatibility_dir)
            .with_context(|| format!("create {}", compatibility_dir.display()))?;
    }
    // The page states what this build supports, so a missing or unparsable
    // baseline has to stop the generator rather than publish a page that quietly
    // says "unknown".
    let baseline = spec_baseline().context("the committed spec baseline must parse")?;
    let changes = spec_changes().context("the committed spec changes must parse")?;
    let problems = gtfs_guru_core::validate_spec_changes(changes, &surface, baseline);
    if !problems.is_empty() {
        bail!(
            "spec_changes.json disagrees with this build, so the compatibility page would \
             publish a false claim:\n  {}",
            problems.join("\n  ")
        );
    }
    check_or_write(
        &compatibility_dir.join("index.html"),
        &render_compatibility_page(&schemas, &surface, baseline, changes),
        check,
        &mut changed,
    )?;

    let expected_codes: BTreeSet<&str> = schemas.keys().map(String::as_str).collect();
    if notices_dir.is_dir() {
        for entry in
            fs::read_dir(&notices_dir).with_context(|| format!("read {}", notices_dir.display()))?
        {
            let entry = entry?;
            if !entry.file_type()?.is_dir() {
                continue;
            }
            let name = entry.file_name();
            let name = name.to_string_lossy();
            if !expected_codes.contains(name.as_ref()) {
                changed.push(entry.path());
            }
        }
    }

    check_or_write(
        &root.join("sitemap.xml"),
        &render_sitemap(&root, &schemas)?,
        check,
        &mut changed,
    )?;

    check_or_write(
        &manifest_dir.join("../../docs/rules.md"),
        &render_rules_markdown(&schemas),
        check,
        &mut changed,
    )?;

    if check && !changed.is_empty() {
        let paths = changed
            .iter()
            .map(|path| format!("  {}", path.display()))
            .collect::<Vec<_>>()
            .join("\n");
        bail!(
            "generated notice pages or rule documentation are stale; run `cargo run -p gtfs-guru-web \
             --bin generate-notice-pages`\n{paths}"
        );
    }

    if !check {
        println!("Generated {} notice pages in website/", schemas.len());
    }
    Ok(())
}

fn render_rules_markdown(schemas: &BTreeMap<String, NoticeSchema>) -> String {
    let mut errors = Vec::new();
    let mut warnings = Vec::new();
    let mut info = Vec::new();

    for schema in schemas.values() {
        match schema.severity_level {
            NoticeSchemaSeverity::Error => errors.push(schema.code.as_str()),
            NoticeSchemaSeverity::Warning => warnings.push(schema.code.as_str()),
            NoticeSchemaSeverity::Info => info.push(schema.code.as_str()),
        }
    }

    let mut output = format!(
        "# Validation Rules\n\n\
         GTFS Guru registers **{REGISTERED_VALIDATOR_COUNT} validators**, which currently emit the **{} notice\n\
         codes** listed below.\n\n\
         This list is generated from the validator's notice schema. To export the full\n\
         machine-readable schema, including context fields for every code:\n\n\
         ```bash\n\
         gtfs-guru --export-notices-schema --output_base ./out\n\
         ```\n\n\
         Which specification revision and canonical validator release these codes are\n\
         aligned with, which of them correspond to a canonical rule, and what changed\n\
         upstream recently: see [the compatibility page](https://gtfs.guru/compatibility/).\n",
        schemas.len()
    );

    for (severity, codes) in [("ERROR", errors), ("WARNING", warnings), ("INFO", info)] {
        write!(output, "\n## {severity} ({})\n\n", codes.len()).expect("write to string");
        for code in codes {
            writeln!(output, "- `{code}`").expect("write to string");
        }
    }

    output
}

fn check_or_write(
    path: &Path,
    content: &str,
    check: bool,
    changed: &mut Vec<PathBuf>,
) -> anyhow::Result<()> {
    let current = fs::read_to_string(path).ok();
    if current.as_deref() == Some(content) {
        return Ok(());
    }
    if check {
        changed.push(path.to_path_buf());
        return Ok(());
    }
    fs::write(path, content).with_context(|| format!("write {}", path.display()))
}

