fn render_sitemap(root: &Path, schemas: &BTreeMap<String, NoticeSchema>) -> anyhow::Result<String> {
    let mut urls = BTreeSet::new();
    urls.insert(format!("{BASE_URL}/"));
    for entry in fs::read_dir(root).with_context(|| format!("read {}", root.display()))? {
        let path = entry?.path();
        if path.extension().and_then(|value| value.to_str()) != Some("html") {
            continue;
        }
        let name = path
            .file_name()
            .and_then(|value| value.to_str())
            .unwrap_or("");
        if name != "index.html" {
            urls.insert(format!("{BASE_URL}/{name}"));
        }
    }
    urls.insert(format!("{BASE_URL}/notices/"));
    for code in schemas.keys() {
        urls.insert(format!("{BASE_URL}/notices/{code}/"));
    }

    let mut xml = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    xml.push_str("<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\n");
    for url in urls {
        writeln!(xml, "  <url><loc>{}</loc></url>", escape_xml(&url)).expect("write to string");
    }
    xml.push_str("</urlset>\n");
    Ok(xml)
}

fn build_related_notices(
    schemas: &BTreeMap<String, NoticeSchema>,
) -> BTreeMap<String, Vec<String>> {
    let mut result = BTreeMap::new();
    for (code, schema) in schemas {
        let files = notice_files(schema.references.as_ref());
        let tokens = code_tokens(code);
        let mut candidates = schemas
            .iter()
            .filter(|(other_code, _)| *other_code != code)
            .map(|(other_code, other)| {
                let other_files = notice_files(other.references.as_ref());
                let file_overlap = files.intersection(&other_files).count();
                let token_overlap = tokens.intersection(&code_tokens(other_code)).count();
                let severity_match =
                    severity_label(schema.severity_level) == severity_label(other.severity_level);
                let score = file_overlap * 6 + token_overlap * 3 + usize::from(severity_match);
                (Reverse(score), other_code.clone())
            })
            .collect::<Vec<_>>();
        candidates.sort();
        result.insert(
            code.clone(),
            candidates
                .into_iter()
                .filter(|(Reverse(score), _)| *score > 0)
                .take(4)
                .map(|(_, code)| code)
                .collect(),
        );
    }
    result
}

fn code_tokens(code: &str) -> BTreeSet<&str> {
    const IGNORED: &[&str] = &[
        "a", "and", "for", "from", "has", "in", "invalid", "missing", "of", "or", "the", "to",
        "too", "with", "without",
    ];
    code.split('_')
        .filter(|token| token.len() > 2 && !IGNORED.contains(token))
        .collect()
}

fn notice_files(references: Option<&ReferencesSchema>) -> BTreeSet<String> {
    let mut files = BTreeSet::new();
    if let Some(references) = references {
        files.extend(references.file_references.iter().cloned());
        files.extend(references.best_practices_file_references.iter().cloned());
    }
    files
}

fn specification_links(references: Option<&ReferencesSchema>) -> BTreeSet<(String, String)> {
    let mut links = BTreeSet::new();
    if let Some(references) = references {
        for file in &references.file_references {
            links.insert((
                format!("GTFS Schedule Reference — {file}"),
                gtfs_file_url(file, false),
            ));
        }
        for file in &references.best_practices_file_references {
            links.insert((
                format!("GTFS Schedule Best Practices — {file}"),
                gtfs_file_url(file, true),
            ));
        }
        for section in &references.section_references {
            links.insert((
                format!("GTFS Schedule Reference — {}", humanize_section(section)),
                format!("https://gtfs.org/documentation/schedule/reference/#{section}"),
            ));
        }
        for reference in &references.url_references {
            links.insert((reference.label.clone(), reference.url.clone()));
        }
    }
    links
}

fn gtfs_file_url(file: &str, best_practices: bool) -> String {
    let anchor = file
        .chars()
        .filter(|character| character.is_ascii_alphanumeric())
        .collect::<String>()
        .to_ascii_lowercase();
    let page = if best_practices {
        "schedule-best-practices"
    } else {
        "reference"
    };
    format!("https://gtfs.org/documentation/schedule/{page}/#{anchor}")
}

fn humanize_section(section: &str) -> String {
    section
        .split('-')
        .map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|first| first.to_uppercase().collect::<String>() + chars.as_str())
                .unwrap_or_default()
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn format_field_type(field_type: &FieldTypeSchema) -> String {
    if field_type.field_type != "array" {
        return field_type.field_type.clone();
    }
    let item = field_type
        .contains
        .as_deref()
        .map(format_field_type)
        .unwrap_or_else(|| "value".to_string());
    match (field_type.min_items, field_type.max_items) {
        (Some(min), Some(max)) if min == max => format!("array<{item}, {min}>"),
        (Some(min), Some(max)) => format!("array<{item}, {min}–{max}>"),
        _ => format!("array<{item}>"),
    }
}

fn severity_label(severity: NoticeSchemaSeverity) -> &'static str {
    match severity {
        NoticeSchemaSeverity::Error => "ERROR",
        NoticeSchemaSeverity::Warning => "WARNING",
        NoticeSchemaSeverity::Info => "INFO",
    }
}

fn generic_impact(severity: NoticeSchemaSeverity) -> &'static str {
    match severity {
        NoticeSchemaSeverity::Error => {
            "This is a GTFS requirement violation. Consumers may reject the affected data or interpret it incorrectly."
        }
        NoticeSchemaSeverity::Warning => {
            "The feed may still load, but correcting this warning improves data quality and the rider experience."
        }
        NoticeSchemaSeverity::Info => {
            "This finding is not necessarily invalid, but it is worth reviewing because it can reveal stale or unexpected data."
        }
    }
}

fn render_rich_text(value: &str) -> String {
    let value = value.split("<table").next().unwrap_or(value).trim();
    let mut out = String::new();
    let mut paragraph = Vec::new();
    let mut list_open = false;

    let flush_paragraph = |out: &mut String, paragraph: &mut Vec<String>| {
        if paragraph.is_empty() {
            return;
        }
        let text = paragraph.join(" ");
        writeln!(out, "<p>{}</p>", render_inline(&text)).expect("write to string");
        paragraph.clear();
    };

    for line in value.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            flush_paragraph(&mut out, &mut paragraph);
            if list_open {
                out.push_str("</ul>\n");
                list_open = false;
            }
        } else if let Some(item) = trimmed.strip_prefix("- ") {
            flush_paragraph(&mut out, &mut paragraph);
            if !list_open {
                out.push_str("<ul>\n");
                list_open = true;
            }
            writeln!(out, "<li>{}</li>", render_inline(item)).expect("write to string");
        } else {
            paragraph.push(trimmed.to_string());
        }
    }
    flush_paragraph(&mut out, &mut paragraph);
    if list_open {
        out.push_str("</ul>\n");
    }
    out
}

fn render_inline(value: &str) -> String {
    let mut out = String::new();
    let mut in_code = false;
    for part in value.split('`') {
        if in_code {
            write!(out, "<code>{}</code>", escape_html(part)).expect("write to string");
        } else {
            out.push_str(&escape_html(part));
        }
        in_code = !in_code;
    }
    out
}

fn truncate_meta(value: &str) -> String {
    const LIMIT: usize = 158;
    if value.chars().count() <= LIMIT {
        return value.to_string();
    }
    let truncated = value.chars().take(LIMIT - 1).collect::<String>();
    let boundary = truncated.rfind(' ').unwrap_or(truncated.len());
    format!("{}…", &truncated[..boundary])
}

fn escape_html(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}

fn escape_xml(value: &str) -> String {
    escape_html(value)
}

